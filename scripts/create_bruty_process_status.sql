CREATE TABLE IF NOT EXISTS public.bruty_status_dev
(
    status_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    description TEXT,
    request_exit BOOLEAN NOT NULL DEFAULT FALSE,
    request_pause BOOLEAN NOT NULL DEFAULT FALSE,
    is_paused BOOLEAN NOT NULL DEFAULT FALSE,
    tile_id BIGINT,
    res_id BIGINT,
    combine_id BIGINT,
    pid INTEGER,
    parent_pid INTEGER,
    progress REAL,
    host TEXT,

    CONSTRAINT status_tile_fk
        FOREIGN KEY (tile_id)
        REFERENCES public.spec_tiles (t_id),

    CONSTRAINT status_res_fk
        FOREIGN KEY (res_id)
        REFERENCES public.spec_resolutions (r_id),

    CONSTRAINT status_combine_fk
        FOREIGN KEY (combine_id)
        REFERENCES public.spec_combines (c_id),

    CONSTRAINT progress_range
        CHECK (
            progress IS NULL
            OR progress BETWEEN 0 AND 100
        )
);

